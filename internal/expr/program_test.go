// TestErrorHelper follows JE-17's decision list for error.
func TestErrorHelper(t *testing.T) {
	p := NewPipeline(realEngine(t, DefaultLimits(), 1))
	for prev, want := range map[string]string{
		`{"error":{"message":"boom"}}`:  `{"message":"boom"}`,
		`{"error":"stopped"}`:           `"stopped"`,
		`{"error":0,"x":1}`:             `{"name":"UnknownError","message":"Could not parse the error","error":{"error":0,"x":1}}`,
		`[]`:                            `{"name":"MultipleErrors","message":"Could not parse errors","errors":[]}`,
		`[1,{"error":{"message":"a"}}]`: `{"message":"a"}`,
		`[{"error":{"step_id":"s","message":"m"}},2,{"error":{"name":"N"}},{"error":null}]`: `{"name":"MultipleErrors","message":"[s] m; [1] N; [2] undefined","errors":[{"error":{"step_id":"s","message":"m"}},2,{"error":{"name":"N"}},{"error":null}]}`,
		// spec: JE-17/d — the entry's fallbacks are falsy tests.
		`[{"error":{"step_id":"","message":"","name":"N"}},{"error":{"message":"m"}}]`: `{"name":"MultipleErrors","message":"[0] N; [1] m","errors":[{"error":{"step_id":"","message":"","name":"N"}},{"error":{"message":"m"}}]}`,
		`[{"error":{"step_id":0,"message":"m"}},{"error":{}}]`:                         `{"name":"MultipleErrors","message":"[0] m; [1] undefined","errors":[{"error":{"step_id":0,"message":"m"}},{"error":{}}]}`,
		`[{"error":{"step_id":"s","name":""}},{"error":{"message":0,"name":"N"}}]`:     `{"name":"MultipleErrors","message":"[s] ; [1] N","errors":[{"error":{"step_id":"s","name":""}},{"error":{"message":0,"name":"N"}}]}`,
		`{}`:   `{"name":"UnknownError","message":"Could not parse the error","error":{}}`,
		`null`: `{"name":"UnknownError","message":"No error found"}`,
		`0`:    `{"name":"UnknownError","message":"No error found"}`,
		`""`:   `{"name":"UnknownError","message":"No error found"}`,
	} {
		s := &Scope{Context: []Named{{"previous_result", value(prev)}}}
		if got, err := evalOn(t, p, SiteInputTransform, "error", s); err != nil || got != want {
			t.Errorf("previous_result %s: error is %s, %v; want %s", prev, got, err, want)
		}
	}
	// error is a lexical binding, not a property of globalThis (JE-10),
	// and is the same value as previous_result.error.
	s := &Scope{Context: []Named{{"previous_result", value(`{"error":{"m":1}}`)}}}
	expectEval(t, p, SiteInputTransform, s, map[string]string{
		"[typeof error, typeof globalThis.error, error === previous_result.error]": `["object","undefined",true]`,
	})
	// Without error in the text, no error is defined.
	expectEval(t, p, SiteInputTransform, s, map[string]string{
		`typeof globalThis["err" + "or"]`: `"undefined"`,
		`eval("err" + "or")`:              "error: QuickJS evaluation error: Error: error is not defined",
	})
	// spec: JE-10/e — error is a let binding, which the expression may
	// assign; results is a constant.
	s.Results = &fakeResults{}
	expectEval(t, p, SiteInputTransform, s, map[string]string{
		`(error = "e", error)`: `"e"`,
		`(results = 1, 2)`:     "error: QuickJS evaluation error: Error: 'results' is read-only\n",
	})
}

