// TestJE8KeyOrderOnEngine extends ADR 0003's JE-8 example (review item
// cx R16) to the engine's routes: step p returns {"b":1,"a":2}. On the
// engine, the proxy answers the previous step from memory (JE-18 rule 1),
// so its keys keep the producer's order, while a step read through the
// database has jsonb's (JE-44, JE-V6).
func TestJE8KeyOrderOnEngine(t *testing.T) {
	p := NewPipeline(realEngine(t, DefaultLimits(), 1))
	producer := `{"b":1,"a":2}`
	r := &fakeResults{stored: map[string]string{"p": `{"a": 2, "b": 1}`}}
	memory := &Scope{PreviousID: "p", Context: []Named{{"previous_result", value(producer)}}, Results: r}
	database := &Scope{PreviousID: "m", Context: []Named{{"previous_result", value("null")}}, Results: r}
	for _, tc := range []struct {
		s    *Scope
		want string
	}{{memory, producer}, {database, `{"a":2,"b":1}`}} {
		got, err := evalOn(t, p, SiteInputTransform, "(results.p)", tc.s)
		if err != nil || got != tc.want {
			t.Errorf("(results.p) after %s: %s, %v; want %s", tc.s.PreviousID, got, err, tc.want)
		}
	}
	if len(r.asked) != 1 || r.asked[0] != "lookup:p" {
		t.Errorf("the database was asked %q, want only the second read", r.asked)
	}
}

// TestHelpersOnEngine covers JE-20 on the engine: each helper resolves to
// its value, a failure throws the API's text from the helper's frame, and
