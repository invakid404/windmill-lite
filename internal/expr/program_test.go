// TestJobQueue follows JE-51: the job queue empties before the result is
// read, in the order jobs were queued; a job that throws is dropped, and a
// rejected promise that is not the result fails nothing.
func TestJobQueue(t *testing.T) {
	p := NewPipeline(realEngine(t, DefaultLimits(), 1))
	expectEval(t, p, SiteInputTransform, nil, map[string]string{
		// spec: JE-51/a
		`((q) => (q(() => { throw new Error("job") }), 1))(queueMicrotask)`: "1",
		// The jobs queued before the serialising reaction run before it.
		"((q, a) => (q(() => a.push(1)), Promise.resolve().then(() => a.push(2)), a))(queueMicrotask, [])": "[1,2]",
		`(Promise.reject(new Error("x")), 1)`: "1",
		// Jobs queued after the value settled still run, a throwing one
		// among them, before the evaluation ends.
		`((q, a) => (Promise.resolve().then(() => q(() => { throw a })), 2))(queueMicrotask, new Error("late"))`: "2",
	})
	// A chain of jobs that never ends keeps the evaluation from finishing
	// after its value settled, until the attempt limit (JE-2).
	l := DefaultLimits()
	l.Attempt = 100 * time.Millisecond
	p = NewPipeline(realEngine(t, l, 1))
	setRetry(p, 1, 0)
	_, err := evalOn(t, p, SiteInputTransform, "((q, f) => (f = () => q(f), f(), 1))(queueMicrotask)", nil)
	if !errors.Is(err, ErrAttemptTimeout) {
		t.Errorf("an endless job chain: %v, want the time limit", err)
	}
}

