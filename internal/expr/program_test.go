// TestReadbackRunsNoCode: reading a thrown value back runs none of the
// program's code beyond what Windmill's embedding runs, an Error's message
// and stack (JE-21; review round 1, R1-1). Each hook here would loop until
// the attempt limit if it were called, so an evaluation that ends with the
// value's text shows that none was.
func TestReadbackRunsNoCode(t *testing.T) {
	l := DefaultLimits()
	l.Attempt = 200 * time.Millisecond
	p := NewPipeline(realEngine(t, l, 1))
	setRetry(p, 1, 0)
	for text, kind := range map[string]string{
		"(() => { throw {toString() { for (;;) {} }, valueOf() { for (;;) {} }} })()":                                                              "Object",
		"(() => { throw {[Symbol.toPrimitive]() { for (;;) {} }} })()":                                                                             "Object",
		"(() => { throw new Proxy({}, {get() { for (;;) {} }, getPrototypeOf() { for (;;) {} }, getOwnPropertyDescriptor() { for (;;) {} }}) })()": "Proxy",
		"(() => { throw Object.assign([1], {toString() { for (;;) {} }}) })()":                                                                     "Array",
		"(() => { const f = () => 1; f.toString = () => { for (;;) {} }; throw f })()":                                                             "Function",
		"(() => { Symbol.prototype.toString = () => { for (;;) {} }; throw Symbol('s') })()":                                                       "Symbol",
	} {
		_, err := evalOn(t, p, SiteInputTransform, text, nil)
		if want := regexp.MustCompile(`^QuickJS evaluation error: Exception generated by quickjs: ` + kind + `\(0x[0-9a-f]+\)\n$`); err == nil || !want.MatchString(err.Error()) {
			t.Errorf("%q: %q, want %s(0x…)", text, err, kind)
		}
	}
	// An Error's name, its toString and a Proxy on its prototype chain are
	// not read; the message and the stack are, before anything else, so a
	// getter elsewhere cannot change the message.
	for text, want := range map[string]string{
		`(() => { const e = new Error("m"); Object.defineProperty(e, "name", {get() { for (;;) {} }}); e.stack = undefined; throw e })()`:                                                                 "QuickJS evaluation error: Error: m",
		`(() => { const e = new Error("m"); Object.defineProperty(e, "name", {get() { e.message = "changed"; return "N" }}); e.stack = ""; throw e })()`:                                                  "QuickJS evaluation error: Error: m\n",
		`(() => { const e = new Error("m"); e.toString = () => { for (;;) {} }; e.stack = undefined; throw e })()`:                                                                                        "QuickJS evaluation error: Error: m",
		`(() => { const e = new Error("m"); e.stack = undefined; Object.setPrototypeOf(e, new Proxy(Error.prototype, {get() { for (;;) {} }, getOwnPropertyDescriptor() { for (;;) {} }})); throw e })()`: "QuickJS evaluation error: Error: m",
	} {
		_, err := evalOn(t, p, SiteInputTransform, text, nil)
		if err == nil || err.Error() != want {
			t.Errorf("%q: %q, want %q", text, err, want)
		}
	}
	// A getter on the message itself is Windmill's to run: it reads the
	// message, so a message getter that loops reaches the limit there too.
	_, err := evalOn(t, p, SiteInputTransform, `(() => { const e = new Error("m"); Object.defineProperty(e, "message", {get() { for (;;) {} }}); throw e })()`, nil)
	if !errors.Is(err, ErrAttemptTimeout) {
		t.Errorf("a message getter that loops: %v, want the time limit", err)
	}
}
