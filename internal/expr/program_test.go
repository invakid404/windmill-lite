// evalOn evaluates text at site in s on p, and returns the producer text or
// the error's.
func evalOn(t *testing.T, p *Pipeline, site SiteKind, text string, s *Scope) (string, error) {
	t.Helper()
	v, err := p.Eval(context.Background(), Compile(site, text), s)
	return string(v.Producer()), err
}

// expectEval holds text to its value, or to an error whose message starts
// with want's "error: " remainder.
func expectEval(t *testing.T, p *Pipeline, site SiteKind, s *Scope, cases map[string]string) {
	t.Helper()
	for text, want := range cases {
		got, err := evalOn(t, p, site, text, s)
		if msg, ok := strings.CutPrefix(want, "error: "); ok {
			if err == nil || !strings.HasPrefix(err.Error(), msg) {
				t.Errorf("%q: %s, %v; want an error starting %q", text, got, err, msg)
			}
			continue
		}
		if err != nil || got != want {
			t.Errorf("%q: %s, %v; want %s", text, got, err, want)
		}
	}
}

