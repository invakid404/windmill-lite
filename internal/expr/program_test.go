// TestJE49OnEngine follows JE-49: a bound context value nested deeper than
// 127 levels fails before any JavaScript runs, with serde_json's text and
// the position of the bracket that goes past the limit, brackets in
// strings not counting, and a shortcut passes any depth through. The
// position counts in the text serde_json reads: a context value's and a
// flow_env member's own text as held, and for flow_input the object
// written out again compactly with its keys escaped as serde_json escapes
// them and its members' texts copied in. When several values are too deep,
// the first in Windmill's order is reported: the context values the text
// names, then previous_result bound by error or a spelling of the previous
// id, then flow_input, then flow_env's members.
func TestJE49OnEngine(t *testing.T) {
	p := NewPipeline(realEngine(t, DefaultLimits(), 1))
	nest := func(k int) string { return strings.Repeat("[", k) + strings.Repeat("]", k) }
	// lined is 128 levels deep, its deepest bracket at line 2, column 127,
	// and lined3 at line 3, column 127.
	lined := "[\n" + nest(127) + "]"
	lined3 := "[\n\n" + nest(127) + "]"
	for _, tc := range []struct {
		name, text string
		s          *Scope
		want       string
	}{
		{"127 levels bind", "previous_result.length", &Scope{Context: []Named{{"previous_result", value(nest(127))}}}, "1"},
		{"128 levels fail", "previous_result.length", &Scope{Context: []Named{{"previous_result", value(nest(128))}}}, "error: recursion limit exceeded at line 1 column 128"},
		{"lines are counted", "previous_result.length", &Scope{Context: []Named{{"previous_result", value("[\n " + nest(127) + "]")}}}, "error: recursion limit exceeded at line 2 column 128"},
		{"strings do not count", "previous_result.length", &Scope{Context: []Named{{"previous_result", value(`["` + strings.Repeat("[", 200) + `"]`)}}}, "1"},
		{"flow_input's object is a level", "flow_input.a.length", &Scope{FlowInput: value(`{"a": ` + nest(127) + `}`)}, "error: recursion limit exceeded at line 1 column 132"},
		{"flow_input's members keep their text", "flow_input.a.length", &Scope{FlowInput: value(`{"a": {"k": ` + nest(126) + `}}`)}, "error: recursion limit exceeded at line 1 column 137"},
		{"flow_input's keys before the member count", "flow_input.a.length", &Scope{FlowInput: value(`{"b": [1, 2], "a": ` + nest(127) + `}`)}, "error: recursion limit exceeded at line 1 column 143"},
		{"flow_input's keys are written again", "flow_input.A.length", &Scope{FlowInput: value(`{"\u0041": ` + nest(127) + `}`)}, "error: recursion limit exceeded at line 1 column 132"},
		{"flow_env's members alone", "flow_env.a.length", &Scope{FlowEnv: value(`{"a":` + nest(127) + `}`)}, "1"},
		{"a deep flow_env member", "flow_env.a.length", &Scope{FlowEnv: value(`{"a":` + nest(128) + `}`)}, "error: recursion limit exceeded at line 1 column 128"},
		{"a flow_env member's own text", "flow_env.a.length", &Scope{FlowEnv: value(`{"a": ` + lined + `}`)}, "error: recursion limit exceeded at line 2 column 127"},
		{"a flow_env member past any parser's limit", "flow_env.a.length", &Scope{FlowEnv: value(`{"b": 1, "a": ` + nest(20000) + `}`)}, "error: recursion limit exceeded at line 1 column 128"},
		{"flow_env's members in their order", "flow_env.a.length", &Scope{FlowEnv: value(`{"z": ` + lined3 + `, "a": ` + nest(128) + `}`)}, "error: recursion limit exceeded at line 3 column 127"},
		{"named context values before flow_input", "previous_result.length + flow_input.a.length", &Scope{Context: []Named{{"previous_result", value(lined)}}, FlowInput: value(`{"a":` + nest(127) + `}`)}, "error: recursion limit exceeded at line 2 column 127"},
		{"named context values in the scope's order", "result.length + previous_result.length", &Scope{Context: []Named{{"result", value(nest(128))}, {"previous_result", value(lined)}}}, "error: recursion limit exceeded at line 1 column 128"},
		{"previous_result bound by error after the named values", "result.length + typeof error", &Scope{Context: []Named{{"previous_result", value(lined)}, {"result", value(nest(128))}}}, "error: recursion limit exceeded at line 1 column 128"},
		{"previous_result bound by error before flow_input", "flow_input.a.length + typeof error", &Scope{Context: []Named{{"previous_result", value(lined)}}, FlowInput: value(`{"a":` + nest(127) + `}`)}, "error: recursion limit exceeded at line 2 column 127"},
		{"flow_input before flow_env", "flow_input.a.length + flow_env.a.length", &Scope{FlowInput: value(`{"a":` + nest(127) + `}`), FlowEnv: value(`{"a": ` + lined + `}`)}, "error: recursion limit exceeded at line 1 column 132"},
		{"only bound values", "1", &Scope{Context: []Named{{"previous_result", value(nest(200))}}}, "1"},
		{"a shortcut", "previous_result", &Scope{Context: []Named{{"previous_result", value(nest(200))}}}, nest(200)},
	} {
		got, err := evalOn(t, p, SiteInputTransform, tc.text, tc.s)
		if msg, ok := strings.CutPrefix(tc.want, "error: "); ok {
			if err == nil || err.Error() != msg || !errors.Is(err, ErrTooDeep) {
				t.Errorf("%s: %s, %v; want %q", tc.name, got, err, msg)
			}
		} else if err != nil || got != tc.want {
			t.Errorf("%s: %s, %v; want %s", tc.name, got, err, tc.want)
		}
	}
}

// TestJE48OnEngine shows deviation D17 of ADR 0001: the stack limit is
// Windmill's 1 MiB, and recursions of depth 600 fit on both engines, but
// this engine's frames also fit the recursion of depth 1 000 that
// overflows on the oracle (JE-48/a, recorded by E3a). Far deeper recursion
// overflows on both, and the depth this engine reaches is logged.
func TestJE48OnEngine(t *testing.T) {
	p := NewPipeline(realEngine(t, DefaultLimits(), 1))
	shape := func(n string) string {
		return "((f) => f(f, " + n + "))((g, n) => n === 0 ? 0 : 1 + g(g, n - 1))"
	}
	if got, err := evalOn(t, p, SiteInputTransform, shape("600"), nil); err != nil || got != "600" {
		t.Errorf("depth 600: %s, %v", got, err)
	}
	if got, err := evalOn(t, p, SiteInputTransform, shape("1000"), nil); err != nil || got != "1000" {
		t.Errorf("depth 1 000 (D17): %s, %v", got, err)
	}
	if _, err := evalOn(t, p, SiteInputTransform, shape("1000000"), nil); err == nil || !strings.HasPrefix(err.Error(), "QuickJS evaluation error: Error: Maximum call stack size exceeded") {
		t.Errorf("depth 1 000 000: %v", err)
	}
	lo, hi := 1000, 100000
	for lo+1 < hi {
		mid := (lo + hi) / 2
		if _, err := evalOn(t, p, SiteInputTransform, shape(strconv.Itoa(mid)), nil); err != nil {
			hi = mid
		} else {
			lo = mid
		}
	}
	t.Logf("%s engine: the deepest recursion of JE-48's shape that fits is %d (the oracle's is below 1000)", testCLibrary, lo)
}

