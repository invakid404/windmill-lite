// undefined throw as running out of memory (JE-3).
func TestErrorTexts(t *testing.T) {
	p := NewPipeline(realEngine(t, DefaultLimits(), 1))
	generated := func(form string) string {
		return "QuickJS evaluation error: Exception generated by quickjs: " + form + "\n"
	}
	for text, want := range map[string]string{
		"null.x":                                 "QuickJS evaluation error: Error: cannot read property 'x' of null\n    at <anonymous> (eval_script:1:1)\n    at <eval> (eval_script:1:35)\n",
		"(() => { throw new TypeError('t') })()": "QuickJS evaluation error: Error: t\n    at <anonymous> (eval_script:1:46)\n    at <anonymous> (eval_script:1:61)\n    at <eval> (eval_script:1:67)\n",
		"(() => { const e = new Error('m'); e.stack = undefined; throw e })()": "QuickJS evaluation error: Error: m",
		"(() => { throw new Error() })()":                                      "QuickJS evaluation error: Error: \n    at <anonymous> (eval_script:1:46)\n    at <anonymous> (eval_script:1:54)\n    at <eval> (eval_script:1:60)\n",
		"(() => { throw undefined })()":                                        memoryMessage(DefaultLimits()),
		"Promise.reject(null)":                                                 memoryMessage(DefaultLimits()),
		"bad!!!syntax":                                                         "QuickJS evaluation error: Error: expecting ';'\n    at eval_script:1:7\n",
		// The message and the stack are read as strings, by conversion;
		// one that is null or undefined, or does not convert, is left out.
		"(() => { const e = new Error('m'); e.message = 5; e.stack = 7; throw e })()":            "QuickJS evaluation error: Error: 5\n7",
		"(() => { const e = new Error('m'); e.message = null; e.stack = undefined; throw e })()": "QuickJS evaluation error: Error:",
		"(() => { const e = new Error('m'); e.message = Symbol(); e.stack = ''; throw e })()":    "QuickJS evaluation error: Error:\n",
		// spec: JE-52/a — a message holding an unpaired surrogate is not
		// read, so the stack follows Error: at once.
		`(() => { throw new Error("bad \ud83d") })()`: "QuickJS evaluation error: Error:\n    at <anonymous> (eval_script:1:46)\n    at <anonymous> (eval_script:1:66)\n    at <eval> (eval_script:1:72)\n",
		// spec: JE-21/b — the debug form, not the string form.
		`(() => { throw "s" })()`:        generated(`String(Ok("s"))`),
		`(() => { throw 1 })()`:          generated("Int(1)"),
		`(() => { throw 1.5 })()`:        generated("Float(1.5)"),
		`(() => { throw 1e300 })()`:      generated("Float(1e300)"),
		`(() => { throw NaN })()`:        generated("Float(NaN)"),
		`(() => { throw true })()`:       generated("Bool(true)"),
		`(() => { throw 10n })()`:        generated(`BigInt"BigInt"`),
		`(() => { throw 2 ** 31 })()`:    generated("Float(2147483648.0)"),
		`(() => { throw 0.5 * 2 })()`:    generated("Float(1.0)"),
		`(() => { throw -0 })()`:         generated("Float(-0.0)"),
		`(() => { throw 1e-7 })()`:       generated("Float(1e-7)"),
		`(() => { throw 'a"b\\c\n' })()`: generated(`String(Ok("a\"b\\c\n"))`),
		`(() => { throw "\ud83d" })()`:   generated(`String(Err(Utf8(Utf8Error { valid_up_to: 0, error_len: Some(1) })))`),
		`Promise.reject("r")`:            generated(`String(Ok("r"))`),
	} {
		_, err := evalOn(t, p, SiteInputTransform, text, nil)
		var ee *EvalError
		if !errors.As(err, &ee) || ee.Message != want {
			t.Errorf("%q: %q\nwant %q", text, err, want)
		}
	}
	// Objects, functions and symbols print the engine's address of the
	// value, so only the type name can be compared (JE-21).
	for text, kind := range map[string]string{
		`(() => { throw {} })()`:                "Object",
		`(() => { throw {message: "m"} })()`:    "Object",
		`(() => { throw [1] })()`:               "Array",
		`(() => { throw () => 1 })()`:           "Function",
		`(() => { throw class {} })()`:          "Constructor",
		`(() => { throw function () {} })()`:    "Constructor",
		`(() => { throw Promise.resolve() })()`: "Promise",
		`(() => { throw new Proxy({}, {}) })()`: "Proxy",
		`(() => { throw Symbol("q") })()`:       "Symbol",
	} {
		_, err := evalOn(t, p, SiteInputTransform, text, nil)
		if want := regexp.MustCompile(`^QuickJS evaluation error: Exception generated by quickjs: ` + kind + `\(0x[0-9a-f]+\)\n$`); err == nil || !want.MatchString(err.Error()) {
			t.Errorf("%q: %q, want %s(0x…)", text, err, kind)
		}
	}
}

// TestReplacedSerialisation follows JE-15: the serialisation calls the
// context's JSON.stringify as it is when it runs, so the user's code can
// replace it. The value its call returns is adopted as a promise
// reaction's is, a rejection fails the evaluation, and the fulfilled value
// is the result text when it is a string that reads as UTF-8, checked for
// nothing else, and null otherwise.
func TestReplacedSerialisation(t *testing.T) {
	p := NewPipeline(realEngine(t, DefaultLimits(), 1))
	expectEval(t, p, SiteInputTransform, nil, map[string]string{
		// spec: JE-15/j — the catalogue's five runs.
		`(JSON.stringify = () => "7", 1)`:                                            "7",
		`(JSON.stringify = () => 5, 1)`:                                              "null",
		`(JSON.stringify = () => Promise.resolve("7"), 1)`:                           "7",
		`(JSON.stringify = () => Promise.reject(new Error("serializer failed")), 1)`: "error: QuickJS evaluation error: Error: serializer failed\n",
		`(JSON.stringify = () => "\ud800", 1)`:                                       "null",
		// A string is kept unchecked, JSON or not; the site that reads it
		// reports what it cannot use.
		`(JSON.stringify = () => "not json", 1)`:                        "not json",
		`JSON.stringify = () => '1, "x": 2'; return 0`:                  `1, "x": 2`,
		`Promise.prototype.then = function () { return "{" }; return 1`: "{",
		`JSON.stringify = () => '"\\u0000"'; return 1`:                  `"\u0000"`,
		// Any other value, a thenable's included, reads as null.
		`(JSON.stringify = () => ({then: (f) => f(new String("7"))}), 1)`: "null",
		`(JSON.stringify = () => undefined, 1)`:                           "null",
	})
}

// countingEngine counts evaluations.
type countingEngine struct {
	Engine
	n atomic.Int32
}

func (c *countingEngine) Eval(ctx context.Context, p Program, in Input) ([]byte, error) {
	c.n.Add(1)
	return c.Engine.Eval(ctx, p, in)
}

// TestJE2OnEngine runs JE-2/a's expression with a short attempt limit: it
// is interrupted (D8) and tried three times, and the last attempt's text
// quotes the trimmed expression and the limit.
func TestJE2OnEngine(t *testing.T) {
	l := DefaultLimits()
	l.Attempt = 100 * time.Millisecond
	eng := &countingEngine{Engine: realEngine(t, l, 1)}
	p := NewPipeline(eng)
	setRetry(p, 3, 10*time.Millisecond)
	start := time.Now()
	_, err := evalOn(t, p, SiteInputTransform, " (() => { while (true) {} })() ", nil)
	if want := "The expression evaluation `(() => { while (true) {} })()` took too long to execute (>100ms)"; err == nil || err.Error() != want || !errors.Is(err, ErrAttemptTimeout) {
		t.Fatalf("Eval: %v, want %q", err, want)
	}
	if n := eng.n.Load(); n != 3 || time.Since(start) < 320*time.Millisecond {
		t.Errorf("%d attempts in %v, want 3 with two pauses", n, time.Since(start))
	}
}

