package bundle

import (
	"bytes"
	"encoding/json"
	"fmt"
	"regexp"
	"slices"
	"strings"
	"unicode/utf8"
)

// HostModuleRegistry is the symbol key of the process-wide registry of
// host-provided modules (ADR 0010): globalThis[Symbol.for(...)] is a Map
// from a module's key, as the host contract names it, to the object holding
// its exports (normally its module namespace). The host SDK registers the
// host's own instances; elsewhere the harness registers the bundled copy
// from scripts/bun/provided/.
const HostModuleRegistry = "windmill-lite.hostModules"

// identifierName matches the export names a shim writes without quotes
// (any IdentifierName may follow `as`, reserved words included); every
// other name is written in the string form of ES2022.
var identifierName = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// Shim returns the source of the shim that every bundler resolves imports
// of one host-provided module to (ADR 0010, D12). It takes each export, by
// name, from the module registered under key, as the step module loads; a
// step whose process has no such module fails at that load with
// `host-provided module not registered: <key>`. A shim cannot follow a live
// binding: it holds each value as it was when the step module loaded.
//
// exports are the module's export names, from the build helper's scan;
// "default" is the default export. The output depends only on key and the
// set of names, so one module always gets one shim.
func Shim(key string, exports []string) ([]byte, error) {
	if key == "" || !utf8.ValidString(key) {
		return nil, fmt.Errorf("bundle: invalid host-provided module key %q", key)
	}
	names := slices.Clone(exports)
	slices.Sort(names)
	names = slices.Compact(names)
	for _, n := range names {
		if n == "" || !utf8.ValidString(n) {
			return nil, fmt.Errorf("bundle: host-provided module %s: invalid export name %q", key, n)
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// windmill-lite: the shim of the host-provided module %s (ADR 0010, D12).\n", jsString(key))
	b.WriteString("// Generated by the build; imports of the module resolve here in every bundle.\n")
	fmt.Fprintf(&b, "const registry = globalThis[Symbol.for(%s)];\n", jsString(HostModuleRegistry))
	fmt.Fprintf(&b, "const found = registry instanceof Map ? registry.get(%s) : undefined;\n", jsString(key))
	b.WriteString("if (found === undefined || found === null) {\n")
	fmt.Fprintf(&b, "  throw new Error(%s);\n", jsString("host-provided module not registered: "+key))
	b.WriteString("}\n")
	for i, n := range names {
		fmt.Fprintf(&b, "const x%d = found[%s];\n", i, jsString(n))
	}
	if len(names) == 0 {
		b.WriteString("export {};\n")
		return b.Bytes(), nil
	}
	b.WriteString("export {\n")
	for i, n := range names {
		alias := n
		if !identifierName.MatchString(n) {
			alias = jsString(n)
		}
		fmt.Fprintf(&b, "  x%d as %s,\n", i, alias)
	}
	b.WriteString("};\n")
	return b.Bytes(), nil
}

// lateSpecifier starts the specifier by which a late shim's ES module
// imports its CommonJS module; the key of the host-provided module follows.
// Both bundlers' plugins resolve it to the CommonJS source LateShim wrote.
const lateSpecifier = "windmill-lite:late/"

// LateShim returns the late shim of one host-provided module (ADR 0010):
// what a listed module resolves its imports of the module to when it
// imports it only lazily and is registered before it. That happens only
// when the lazy import closes a cycle, and such an import can run before
// the module is registered, while the earlier modules load.
//
// A bundler initialises a module once, so a plain shim that threw there can
// never yield the registered values later: on Bun 1.3.10 and esbuild, every
// later import gets the shim's exports undefined, and a module without
// exports seems imported although it has not loaded. The late shim reads
// the registry each time one of its values is read instead. A read before
// the module is registered throws LateShimMessage, every time; a read after
// it gets the registered value.
//
// The late shim always has a then export, read from the registry like the
// others: the module's own then when it exports one, undefined otherwise.
// An import() reads then on the namespace it resolves to, so every import()
// of the module before its registration rejects with LateShimMessage, a
// module without exports included, and one after it resolves.
//
// It is two sources. esm, which imports resolve to, re-exports each export
// by name from cjs; cjs defines one getter per export over the registry and
// never throws while it is evaluated.
func LateShim(key string, exports []string) (esm, cjs []byte, err error) {
	if key == "" || !utf8.ValidString(key) {
		return nil, nil, fmt.Errorf("bundle: invalid host-provided module key %q", key)
	}
	names := append(slices.Clone(exports), "then")
	slices.Sort(names)
	names = slices.Compact(names)
	for _, n := range names {
		if n == "" || !utf8.ValidString(n) {
			return nil, nil, fmt.Errorf("bundle: host-provided module %s: invalid export name %q", key, n)
		}
	}
	var e, c bytes.Buffer
	fmt.Fprintf(&e, "// windmill-lite: the late shim of the host-provided module %s (ADR 0010, D12).\n", jsString(key))
	e.WriteString("// Generated by the build for a listed module that imports it lazily and is registered before it.\n")
	e.WriteString("export {\n")
	for i, n := range names {
		alias := n
		if !identifierName.MatchString(n) {
			alias = jsString(n)
		}
		fmt.Fprintf(&e, "  x%d as %s,\n", i, alias)
	}
	fmt.Fprintf(&e, "} from %s;\n", jsString(lateSpecifier+key))

	fmt.Fprintf(&c, "// windmill-lite: the registry reads of the late shim of the host-provided module %s (ADR 0010, D12).\n", jsString(key))
	c.WriteString("function found() {\n")
	fmt.Fprintf(&c, "  const registry = globalThis[Symbol.for(%s)];\n", jsString(HostModuleRegistry))
	fmt.Fprintf(&c, "  const m = registry instanceof Map ? registry.get(%s) : undefined;\n", jsString(key))
	c.WriteString("  if (m === undefined || m === null) {\n")
	fmt.Fprintf(&c, "    throw new Error(%s);\n", jsString(LateShimMessage(key)))
	c.WriteString("  }\n  return m;\n}\n")
	for i, n := range names {
		fmt.Fprintf(&c, "Object.defineProperty(exports, \"x%d\", { enumerable: true, get: () => found()[%s] });\n", i, jsString(n))
	}
	return e.Bytes(), c.Bytes(), nil
}

// LateShimMessage is the message of the error a late shim throws when its
// module is imported, or one of its values read, before the module is
// registered.
func LateShimMessage(key string) string {
	return "host-provided module not registered: " + key +
		" (a listed module registered before it imports it lazily, and used it before its registration)"
}

// jsString is a JavaScript string literal for s.
func jsString(s string) string {
	var b strings.Builder
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		panic(err) // a valid UTF-8 string always encodes
	}
	return strings.TrimSuffix(b.String(), "\n")
}
