var update = flag.Bool("update", false, "rewrite routes.json from the vendored openapi.yaml")

// openapiPath is the Apache-2.0 openapi.yaml vendored with its notice by
// milestone E2.
var openapiPath = filepath.Join("..", "..", "oracle", "openapi", "openapi.yaml")

// TestRouteTable holds routes.json to the vendored openapi.yaml: every
// operation, its method, template and operationId, in a fixed order. With
// -update it rewrites routes.json instead.
func TestRouteTable(t *testing.T) {
	src, err := os.ReadFile(openapiPath)
	if err != nil {
		t.Fatal(err)
	}
	want := generateRoutes(t, src)
	if *update {
		if err := os.WriteFile("routes.json", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if !bytes.Equal(routesJSON, want) {
		t.Fatal("routes.json differs from the vendored openapi.yaml; run go test ./internal/platform/facade -run TestRouteTable -args -update")
	}
}

func generateRoutes(t *testing.T, src []byte) []byte {
	t.Helper()
	var doc struct {
		Paths yaml.Node `yaml:"paths"`
	}
	if err := yaml.Unmarshal(src, &doc); err != nil {
		t.Fatal(err)
	}
	methods := map[string]bool{"get": true, "post": true, "put": true, "delete": true, "patch": true, "head": true, "options": true}
	var routes [][3]string
	p := doc.Paths
	for i := 0; i+1 < len(p.Content); i += 2 {
		path, ops := p.Content[i].Value, p.Content[i+1]
		for j := 0; j+1 < len(ops.Content); j += 2 {
			m := ops.Content[j].Value
			if !methods[m] {
				continue
			}
			op := ""
			body := ops.Content[j+1]
			for k := 0; k+1 < len(body.Content); k += 2 {
				if body.Content[k].Value == "operationId" {
					op = body.Content[k+1].Value
				}
			}
			if op == "" {
				t.Fatalf("%s %s has no operationId", m, path)
			}
			routes = append(routes, [3]string{strings.ToUpper(m), path, op})
		}
	}
	sort.Slice(routes, func(i, j int) bool {
		if routes[i][1] != routes[j][1] {
			return routes[i][1] < routes[j][1]
		}
		return routes[i][0] < routes[j][0]
	})
	sum := sha256.Sum256(src)
	var b bytes.Buffer
	fmt.Fprintf(&b, "{\n  \"about\": %q,\n  \"source\": \"internal/oracle/openapi/openapi.yaml\",\n  \"source_sha256\": %q,\n  \"routes\": [\n",
		"Windmill's REST API routes (method, path template relative to /api, operationId), generated by TestRouteTable from the Apache-2.0 openapi.yaml of Windmill v1.767.0 vendored with its notice in internal/oracle/openapi; route templates are wire-format literals.",
		hex.EncodeToString(sum[:]))
	for i, r := range routes {
		line, err := json.Marshal(r)
		if err != nil {
			t.Fatal(err)
		}
		sep := ","
		if i == len(routes)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    %s%s\n", line, sep)
	}
	b.WriteString("  ]\n}\n")
	return b.Bytes()
}

// TestRouteMatch checks the matching rules on the real table: a trailing
// parameter takes a path with slashes, a literal beats a parameter, path
// parameters are unescaped, and a path no route has does not match.
func TestRouteMatch(t *testing.T) {
	for _, c := range []struct {
		method, path, name string
		params             map[string]string
	}{
		{"GET", "/w/ws/jobs_u/get_root_job_id/j1", "GET /w/{ws}/jobs_u/get_root_job_id/{id}", map[string]string{"workspace": "ws", "id": "j1"}},
		{"GET", "/w/ws/variables/get_value/u/x/v", "GET /w/{ws}/variables/get_value/{path}", map[string]string{"workspace": "ws", "path": "u/x/v"}},
		{"POST", "/w/ws/jobs/run/p/u/t/x", "POST /w/{ws}/jobs/run/p/{path}", map[string]string{"workspace": "ws", "path": "u/t/x"}},
		{"POST", "/w/ws/jobs/flow/user_states/r1/k", "POST /w/{ws}/jobs/flow/user_states/{id}/{key}", map[string]string{"workspace": "ws", "id": "r1", "key": "k"}},
		{"GET", "/w/ws/jobs_u/get/j1", "GET /w/{ws}/jobs_u/get/{id}", map[string]string{"workspace": "ws", "id": "j1"}},
		{"POST", "/w/ws/oidc/token/a%20b", "POST /w/{ws}/oidc/token/{audience}", map[string]string{"workspace": "ws", "audience": "a b"}},
		{"GET", "/version", "GET /version", map[string]string{}},
	} {
		r, params, ok := defaultRoutes.match(c.method, c.path)
		if !ok {
			t.Errorf("%s %s: no route", c.method, c.path)
			continue
		}
		if r.Name() != c.name || fmt.Sprint(params) != fmt.Sprint(c.params) {
			t.Errorf("%s %s: %s %v, want %s %v", c.method, c.path, r.Name(), params, c.name, c.params)
		}
	}
	for _, c := range [][2]string{{"GET", "/w/ws/no_such_route/x"}, {"DELETE", "/w/ws/jobs_u/get_root_job_id/j1"}, {"GET", "/w/ws/jobs_u/get_root_job_id/"}} {
		if r, _, ok := defaultRoutes.match(c[0], c[1]); ok {
			t.Errorf("%s %s matched %s", c[0], c[1], r.Name())
		}
	}
}
