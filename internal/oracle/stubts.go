// The stub source of stub mode (ADR 0011). A stub keeps what Windmill's
// signature parser reads from a Bun script, and nothing that runs:
//
//   - main's parameter list, verbatim: the parser binds arguments by the
//     names it finds there, and the schema the CLI generates comes from it
//     (WR-6, WR-7);
//   - every top-level type alias and interface, verbatim: the parser
//     resolves local aliases to decide which parameters are hydrated as
//     Date (WR-8, WR-V3). Types are erased before the code runs, so they
//     cannot reach the systems the original body talks to.
//
// Everything else (imports, top-level code, the body) is dropped. The scan
// is textual over a small lexer: it decides what is top level by bracket
// depth, so it never mistakes text in strings, comments, templates or
// regular expressions for code. A script it cannot read that way, or
// whose stub could differ from the original before the body runs, is
// refused with the reason.

// StubSource returns the stub of a Bun script's source.
func StubSource(src string) (string, error) {
	m, err := scanTS(src)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(stubHeader)
	for _, d := range m.keep {
		b.WriteString(d)
		b.WriteString("\n\n")
	}
	b.WriteString("export async function main(")
	b.WriteString(m.params)
	b.WriteString(") {\n  return __wlReplay(Array.from(arguments));\n}\n")
	b.WriteString(stubReplay)
	return b.String(), nil
}

const stubHeader = `// Generated by wltest stub (ADR 0011 stub mode). main keeps the original
// parameter list and the file keeps the original's type declarations, so
// Windmill's signature parser binds and hydrates the arguments as before;
// the body asks the run's replay service for the outcome.

`

// stubReplay posts the call to the replay service below WL_EFFECT_SINK
// (conformance.ReplayPath) and returns or throws its outcome. It reads
// the job identities of OR-29 and sends absent ones as null.
const stubReplay = `
async function __wlReplay(args) {
  const env = globalThis.process.env;
  const res = await fetch(env.WL_EFFECT_SINK + "/replay", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({
      root: env.WM_ROOT_JOB_ID ?? null,
      root_flow: env.WM_ROOT_FLOW_JOB_ID ?? null,
      flow: env.WM_FLOW_JOB_ID ?? null,
      job: env.WM_JOB_ID ?? null,
      step: env.WM_FLOW_STEP_ID ?? null,
      args,
    }),
  });
  const text = await res.text();
  if (res.status !== 200) {
    throw new Error("wltest replay refused the call (HTTP " + res.status + "): " + text);
  }
  const outcome = JSON.parse(text);
  if ("error" in outcome) {
    const { name, message, ...extra } = outcome.error;
    const err = new Error(message);
    if (name !== undefined) err.name = name;
    Object.assign(err, extra);
    throw err;
  }
  return outcome.result;
}
`

// stubError is a script StubSource refuses, with the reason.
type stubError struct{ reason string }

func (e *stubError) Error() string { return e.reason }

func refuseTS(format string, a ...any) error { return &stubError{fmt.Sprintf(format, a...)} }

// tsModule is what a stub keeps of a script.
type tsModule struct {
	params string   // main's parameter list, verbatim
	keep   []string // top-level type aliases and interfaces, verbatim
}

type tsKind uint8

const (
	tsIdent tsKind = iota + 1
	tsPunct
	tsString
	tsTemplate
	tsRegex
	tsNumber
)

// tsToken is one token. A template literal is cut at its substitutions:
// a part that ends in "${" opens a nesting level and one that starts with
// "}" closes it, like brackets.
type tsToken struct {
	kind       tsKind
	text       string
	start, end int
	nl         bool // a line terminator comes before it
	open       bool // a template part that ends in "${"
	close      bool // a template part that starts with "}"
}

func (t tsToken) is(kind tsKind, text string) bool { return t.kind == kind && t.text == text }

// delta is the change of nesting depth the token makes.
func (t tsToken) delta() int {
	switch t.kind {
	case tsPunct:
		switch t.text {
		case "(", "[", "{":
			return 1
		case ")", "]", "}":
			return -1
		}
	case tsTemplate:
		d := 0
		if t.open {
			d++
		}
		if t.close {
			d--
		}
		return d
	}
	return 0
}

// punctuators, longest first.
var tsPuncts = []string{
	">>>=", "...", "===", "!==", "**=", "<<=", ">>=", ">>>", "&&=", "||=", "??=",
	"=>", "==", "!=", "<=", ">=", "&&", "||", "??", "?.", "++", "--", "+=", "-=",
	"*=", "%=", "&=", "|=", "^=", "**", "<<", ">>",
}

// keywords after which a "/" starts a regular expression.
var regexAfter = map[string]bool{
	"return": true, "typeof": true, "instanceof": true, "in": true, "of": true, "new": true,
	"delete": true, "void": true, "throw": true, "case": true, "do": true, "else": true,
	"yield": true, "await": true,
}

func isLineTerminator(r rune) bool { return r == '\n' || r == '\r' || r == 0x2028 || r == 0x2029 }

func isIdentStart(r rune) bool {
	return r == '_' || r == '$' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= 0x80 && unicode.IsLetter(r)
}

func isIdentPart(r rune) bool {
	return isIdentStart(r) || r >= '0' && r <= '9' || r >= 0x80 && (unicode.IsDigit(r) || unicode.Is(unicode.Mn, r) || unicode.Is(unicode.Mc, r) || unicode.Is(unicode.Pc, r)) || r == 0x200c || r == 0x200d
}

// lexTS splits TypeScript source into tokens, skipping white space and
// comments.
func lexTS(src string) ([]tsToken, error) {
	var toks []tsToken
	var stack []byte // '{' for a brace, '$' for a template substitution
	nl := false
	i := 0
	if strings.HasPrefix(src, "#!") {
		for i < len(src) && src[i] != '\n' {
			i++
		}
	}
	prevAllowsRegex := func() bool {
		if len(toks) == 0 {
			return true
		}
		p := toks[len(toks)-1]
		switch p.kind {
		case tsIdent:
			return regexAfter[p.text]
		case tsNumber, tsString, tsRegex:
			return false
		case tsTemplate:
			return p.open
		}
		return p.text != ")" && p.text != "]" && p.text != "}"
	}
	emit := func(t tsToken) {
		t.nl = nl
		nl = false
		toks = append(toks, t)
	}
	// template scans a template literal part from i, just after "`" or the
	// "}" that ends a substitution, to the closing "`" or the next "${".
	template := func(start int, closes bool) error {
		for i < len(src) {
			switch src[i] {
			case '\\':
				i += 2
				continue
			case '`':
				i++
				emit(tsToken{kind: tsTemplate, text: src[start:i], start: start, end: i, close: closes})
				return nil
			case '$':
				if i+1 < len(src) && src[i+1] == '{' {
					i += 2
					stack = append(stack, '$')
					emit(tsToken{kind: tsTemplate, text: src[start:i], start: start, end: i, open: true, close: closes})
					return nil
				}
			}
			i++
		}
		return refuseTS("unterminated template literal at offset %d", start)
	}
	for i < len(src) {
		r, size := utf8.DecodeRuneInString(src[i:])
		start := i
		switch {
		case isLineTerminator(r):
			nl = true
			i += size
		case r == ' ' || r == '\t' || r == '\v' || r == '\f' || r == 0xa0 || r == 0xfeff || unicode.Is(unicode.Zs, r):
			i += size
		case r == '/' && i+1 < len(src) && src[i+1] == '/':
			for i < len(src) {
				r, size := utf8.DecodeRuneInString(src[i:])
				if isLineTerminator(r) {
					break
				}
				i += size
			}
		case r == '/' && i+1 < len(src) && src[i+1] == '*':
			end := strings.Index(src[i+2:], "*/")
			if end < 0 {
				return nil, refuseTS("unterminated comment at offset %d", start)
			}
			body := src[i+2 : i+2+end]
			if strings.ContainsAny(body, "\n\r  ") {
				nl = true
			}
			i += end + 4
		case r == '"' || r == '\'':
			i++
			for {
				if i >= len(src) {
					return nil, refuseTS("unterminated string at offset %d", start)
				}
				c, size := utf8.DecodeRuneInString(src[i:])
				if c == '\\' {
					_, s2 := utf8.DecodeRuneInString(src[i+1:])
					i += 1 + s2
					continue
				}
				if isLineTerminator(c) && c != 0x2028 && c != 0x2029 {
					return nil, refuseTS("unterminated string at offset %d", start)
				}
				i += size
				if c == r {
					break
				}
			}
			emit(tsToken{kind: tsString, text: src[start:i], start: start, end: i})
		case r == '`':
			i++
			if err := template(start, false); err != nil {
				return nil, err
			}
		case r == '}' && len(stack) > 0 && stack[len(stack)-1] == '$':
			stack = stack[:len(stack)-1]
			i++
			if err := template(start, true); err != nil {
				return nil, err
			}
		case r == '/' && prevAllowsRegex():
			i++
			class := false
			for {
				if i >= len(src) {
					return nil, refuseTS("unterminated regular expression at offset %d", start)
				}
				c, size := utf8.DecodeRuneInString(src[i:])
				if isLineTerminator(c) {
					return nil, refuseTS("unterminated regular expression at offset %d", start)
				}
				i += size
				if c == '\\' {
					_, s2 := utf8.DecodeRuneInString(src[i:])
					i += s2
					continue
				}
				if c == '[' {
					class = true
				} else if c == ']' {
					class = false
				} else if c == '/' && !class {
					break
				}
			}
			for i < len(src) {
				c, size := utf8.DecodeRuneInString(src[i:])
				if !isIdentPart(c) {
					break
				}
				i += size
			}
			emit(tsToken{kind: tsRegex, text: src[start:i], start: start, end: i})
		case isIdentStart(r) || r == '#' && i+1 < len(src) && isIdentStart(rune(src[i+1])):
			i += size
			for i < len(src) {
				c, size := utf8.DecodeRuneInString(src[i:])
				if !isIdentPart(c) {
					break
				}
				i += size
			}
			emit(tsToken{kind: tsIdent, text: src[start:i], start: start, end: i})
		case r >= '0' && r <= '9' || r == '.' && i+1 < len(src) && src[i+1] >= '0' && src[i+1] <= '9':
			radix := len(src) > i+1 && src[i] == '0' && strings.ContainsRune("xXbBoO", rune(src[i+1]))
			i++
			for i < len(src) {
				c := src[i]
				if (c == '+' || c == '-') && !radix && (src[i-1] == 'e' || src[i-1] == 'E') {
					i++
					continue
				}
				if c == '.' || c == '_' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' {
					i++
					continue
				}
				break
			}
			emit(tsToken{kind: tsNumber, text: src[start:i], start: start, end: i})
		case r == '\\':
			return nil, refuseTS("an escape outside a string or comment at offset %d", start)
		default:
			text := ""
			for _, p := range tsPuncts {
				if strings.HasPrefix(src[i:], p) {
					text = p
					break
				}
			}
			if text == "" {
				if !strings.ContainsRune("{}()[];,<>+-*/%&|^!~?:=.@#", r) {
					return nil, refuseTS("unexpected character %q at offset %d", r, start)
				}
				text = string(r)
			}
			switch text {
			case "{":
				stack = append(stack, '{')
			case "}":
				if len(stack) > 0 {
					stack = stack[:len(stack)-1]
				}
			}
			i += len(text)
			emit(tsToken{kind: tsPunct, text: text, start: start, end: i})
		}
	}
	return toks, nil
}

// scanTS finds main's parameter list and the type declarations a stub
// keeps.
func scanTS(src string) (*tsModule, error) {
	toks, err := lexTS(src)
	if err != nil {
		return nil, err
	}
	m := &tsModule{}
	found := false
	depth := 0
	for i := 0; i < len(toks); i++ {
		t := toks[i]
		if depth == 0 && t.kind == tsIdent {
			switch t.text {
			case "function":
				params, isMain, err := scanFunction(src, toks, i)
				if err != nil {
					return nil, err
				}
				if isMain {
					if found {
						return nil, refuseTS("main is declared more than once (overloads are not supported)")
					}
					found = true
					m.params = params
				}
			case "type", "interface":
				decl, end, ok, err := scanTypeDecl(src, toks, i)
				if err != nil {
					return nil, err
				}
				if ok {
					m.keep = append(m.keep, decl)
					for ; i < end; i++ {
						depth += toks[i].delta()
					}
					depth += toks[end].delta()
					continue
				}
			}
		}
		depth += t.delta()
		if depth < 0 {
			return nil, refuseTS("unbalanced %q at offset %d", t.text, t.start)
		}
	}
	if depth != 0 {
		return nil, refuseTS("unbalanced brackets")
	}
	if !found {
		return nil, refuseTS("no exported function declaration main (an arrow-function main gets no arguments from Windmill, WR-7, and is not supported)")
	}
	return m, nil
}

// statementStart reports whether the token at i begins a statement: it
// is the first token, it follows ";" or "}", or a line break separates it
// from a token that cannot continue an expression.
func statementStart(toks []tsToken, i int) bool {
	if i == 0 {
		return true
	}
	p := toks[i-1]
	if p.is(tsPunct, ";") || p.is(tsPunct, "}") {
		return true
	}
	if !toks[i].nl {
		return false
	}
	switch p.kind {
	case tsIdent, tsNumber, tsString, tsRegex:
		return true
	case tsTemplate:
		return !p.open
	}
	return p.text == ")" || p.text == "]" || p.text == "++" || p.text == "--"
}

// declStart returns the first token of the declaration whose keyword is at
// i: the keyword, or an export, declare or async before it.
func declStart(toks []tsToken, i int, prefixes ...string) int {
	s := i
	for s > 0 {
		p := toks[s-1]
		ok := false
		for _, w := range prefixes {
			if p.is(tsIdent, w) {
				ok = true
			}
		}
		if !ok {
			break
		}
		s--
	}
	return s
}

// scanFunction reads the function declaration at the "function" token i.
// It returns main's parameter list, or isMain false for another function
// or a function expression; and it refuses a main or a preprocessor the
// stub cannot keep.
func scanFunction(src string, toks []tsToken, i int) (params string, isMain bool, err error) {
	n := i + 1
	generator := n < len(toks) && toks[n].is(tsPunct, "*")
	if generator {
		n++
	}
	if n >= len(toks) || toks[n].kind != tsIdent {
		return "", false, nil
	}
	name := toks[n].text
	if name != "main" && name != "preprocessor" {
		return "", false, nil
	}
	s := declStart(toks, i, "async", "export", "default")
	exported := s < i && toks[s].is(tsIdent, "export")
	isDefault := false
	for k := s; k < i; k++ {
		if toks[k].is(tsIdent, "default") {
			isDefault = true
		}
	}
	if !exported && !statementStart(toks, s) {
		return "", false, nil // a function expression
	}
	if name == "preprocessor" {
		return "", false, refuseTS("the script declares a preprocessor, which the stub does not keep (WR-11)")
	}
	switch {
	case isDefault:
		return "", false, refuseTS("main is a default export, which Windmill does not call (WR-7)")
	case !exported:
		return "", false, refuseTS("main is not exported where it is declared")
	case generator:
		return "", false, refuseTS("main is a generator function")
	}
	p := n + 1
	if p >= len(toks) || !toks[p].is(tsPunct, "(") {
		return "", false, refuseTS("main has type parameters or no parameter list; only a plain parameter list is supported")
	}
	close, err := matching(toks, p)
	if err != nil {
		return "", false, err
	}
	if err := checkParams(toks[p+1 : close]); err != nil {
		return "", false, err
	}
	return src[toks[p].end:toks[close].start], true, nil
}

// matching returns the index of the token that closes the opener at i.
func matching(toks []tsToken, i int) (int, error) {
	depth := 0
	for k := i; k < len(toks); k++ {
		depth += toks[k].delta()
		if depth == 0 {
			return k, nil
		}
	}
	return 0, refuseTS("unbalanced %q at offset %d", toks[i].text, toks[i].start)
}

// angles returns the change of type-argument depth a token makes inside a
// type: "<" opens, and each ">" of ">", ">>", ">>>", ">=" … closes.
func angles(t tsToken) int {
	if t.kind != tsPunct {
		return 0
	}
	if t.text == "<" {
		return 1
	}
	if strings.HasPrefix(t.text, ">") {
		return -strings.Count(t.text, ">")
	}
	return 0
}

// defaultWords are the identifiers a parameter default may use besides the
// parameters themselves: literals, operators and standard globals, which
// a stub still has. A default that names anything else may name a binding
// the stub drops, and fail when it applies.
var defaultWords = map[string]bool{
	"true": true, "false": true, "null": true, "undefined": true, "NaN": true, "Infinity": true,
	"new": true, "typeof": true, "void": true, "in": true, "instanceof": true,
	"Date": true, "Math": true, "Number": true, "String": true, "Boolean": true, "Array": true,
	"Object": true, "JSON": true, "BigInt": true, "Symbol": true, "RegExp": true, "Map": true,
	"Set": true, "Error": true, "process": true, "Bun": true, "globalThis": true,
	"parseInt": true, "parseFloat": true,
}

// checkParams refuses a parameter list whose defaults name a binding the
// stub drops, or whose names collide with the stub's helper.
func checkParams(toks []tsToken) error {
	const (
		pattern = iota
		typed
		dflt
	)
	mode, depth, angle := pattern, 0, 0
	names := map[string]bool{}
	for k, t := range toks {
		top := depth == 0
		switch {
		case top && t.is(tsPunct, ",") && (mode != typed || angle == 0):
			mode, angle = pattern, 0
		case mode == pattern && top && t.is(tsPunct, ":"):
			mode = typed
		case mode == pattern && top && t.is(tsPunct, "="):
			mode = dflt
		case mode == pattern && t.kind == tsIdent:
			if strings.HasPrefix(t.text, "__wl") {
				return refuseTS("parameter %s collides with the stub's helper", t.text)
			}
			names[t.text] = true
		case mode == typed && top:
			angle += angles(t)
			if angle == 0 && (t.is(tsPunct, "=") || t.kind == tsPunct && strings.HasPrefix(t.text, ">") && strings.HasSuffix(t.text, "=")) {
				mode = dflt
			}
		case mode == dflt && t.kind == tsIdent:
			member := k > 0 && (toks[k-1].is(tsPunct, ".") || toks[k-1].is(tsPunct, "?."))
			key := k+1 < len(toks) && toks[k+1].is(tsPunct, ":")
			if !defaultWords[t.text] && !names[t.text] && !member && !key {
				return refuseTS("a parameter default names %s, which the stub does not keep; write the value inline", t.text)
			}
		}
		depth += t.delta()
	}
	return nil
}

// typeContinuesAfter are tokens a type cannot end with, so a line break
// after them does not end a type alias.
var typeContinuesAfter = map[string]bool{
	"=": true, "|": true, "&": true, ":": true, "?": true, "=>": true, ",": true, ".": true, "<": true,
	"(": true, "[": true, "{": true, "extends": true, "keyof": true, "typeof": true, "infer": true,
	"readonly": true, "is": true, "asserts": true, "new": true, "in": true, "as": true, "unique": true,
}

// typeContinuesWith are tokens that continue a type on the next line.
var typeContinuesWith = map[string]bool{
	"|": true, "&": true, "?": true, ":": true, ".": true, "?.": true, "=>": true, "[": true, "<": true,
	">": true, "extends": true, ",": true, "as": true, "is": true,
}

// scanTypeDecl reads the type alias or interface whose keyword is at i. It
// returns the declaration's text (with any export or declare before it)
// and the index of its last token; ok is false when the keyword is not a
// declaration there.
func scanTypeDecl(src string, toks []tsToken, i int) (decl string, end int, ok bool, err error) {
	kw := toks[i].text
	n := i + 1
	if n >= len(toks) || toks[n].kind != tsIdent || toks[n].nl {
		return "", 0, false, nil
	}
	s := declStart(toks, i, "export", "declare")
	if s == i && !statementStart(toks, i) {
		return "", 0, false, nil
	}
	k := n + 1
	if kw == "type" {
		if k < len(toks) && toks[k].is(tsPunct, "<") {
			angle := 0
			for ; k < len(toks); k++ {
				angle += angles(toks[k])
				if angle <= 0 {
					break
				}
			}
			k++
		}
		if k >= len(toks) || !toks[k].is(tsPunct, "=") {
			return "", 0, false, nil
		}
		depth, angle := 0, 0
		last := k
		for k++; k < len(toks); k++ {
			t := toks[k]
			if depth == 0 && angle == 0 {
				if t.is(tsPunct, ";") {
					last = k
					break
				}
				if t.nl && !typeContinuesAfter[toks[k-1].text] && !typeContinuesWith[t.text] {
					break
				}
			}
			depth += t.delta()
			if depth == 0 {
				angle += angles(t)
			}
			if depth < 0 {
				return "", 0, false, refuseTS("unbalanced %q in type %s", t.text, toks[n].text)
			}
			last = k
		}
		return src[toks[s].start:toks[last].end], last, true, nil
	}
	// An interface ends at the brace that closes its body.
	angle := 0
	for ; k < len(toks); k++ {
		t := toks[k]
		if angle == 0 && t.is(tsPunct, "{") {
			close, err := matching(toks, k)
			if err != nil {
				return "", 0, false, err
			}
			return src[toks[s].start:toks[close].end], close, true, nil
		}
		if t.delta() != 0 {
			close, err := matching(toks, k)
			if err != nil {
				return "", 0, false, err
			}
			k = close
			continue
		}
		angle += angles(t)
	}
	return "", 0, false, refuseTS("interface %s has no body", toks[n].text)
}
